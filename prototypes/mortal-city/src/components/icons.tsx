// 像素霓虹圖示：12×12 點陣，跟城市的 16-bit sprite 同一套。# ＝主色（currentColor）、+ ＝紅色重點。
// 外觀（紅青錯位殘影、光暈、選中時的故障閃動）在 styles.css 的 .px-icon／.neon。
// 介面跟 lucide 元件相容：size、className；名稱沿用 lucide 的，換 import 來源就好。
export type IconProps = { size?: number; className?: string }

/** 一列一列合併成橫向矩形（同一列連續同色的格子畫成一塊）。 */
function rects(rows: string[], ink: string) {
  const out: [number, number, number][] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== ink) {
        x++
        continue
      }
      let w = 1
      while (row[x + w] === ink) w++
      out.push([x, y, w])
      x += w
    }
  })
  return out
}

export const GRIDS: Record<string, string[]> = {}

function px(name: string, rows: string[]) {
  GRIDS[name] = rows
  const main = rects(rows, '#')
  const accent = rects(rows, '+')
  return function PixelIcon({ size = 20, className = '' }: IconProps) {
    return (
      <svg width={size} height={size} viewBox="0 0 12 12" aria-hidden className={`px-icon shrink-0 ${className}`} shapeRendering="crispEdges">
        <g fill="currentColor">
          {main.map(([x, y, w]) => (
            <rect key={`${x},${y}`} x={x} y={y} width={w} height={1} />
          ))}
        </g>
        <g fill="var(--color-red)">
          {accent.map(([x, y, w]) => (
            <rect key={`${x},${y}`} x={x} y={y} width={w} height={1} />
          ))}
        </g>
      </svg>
    )
  }
}

